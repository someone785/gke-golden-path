#!/usr/bin/env bash
# SLO の定義 (gitops/workloads/otel-demo/slo/*.sloth.yaml) から、Prometheus のルールを Sloth で生成し、
# OpenTelemetry Demo の chart に渡す values (gitops/workloads/otel-demo/values-slo-rules.yaml) にする。
#
# 使い方:
#   scripts/gen-slo-rules.sh          # 生成して上書きする
#   scripts/gen-slo-rules.sh --check  # 生成し直した結果が、Git にあるものと一致するかを検査する (CI 用)
#
# 生成物を Git に置く理由: ArgoCD は Git のファイルをそのまま使うので、Sloth をクラスタで動かさずに済む (ADR 0006)。
# 冪等: 同じ入力からは、同じ出力になる。
set -euo pipefail

cd "$(dirname "$0")/.."

slo_dir="gitops/workloads/otel-demo/slo"
out="gitops/workloads/otel-demo/values-slo-rules.yaml"

tmp="$(mktemp -d)"
trap 'rm -rf "${tmp}"' EXIT

# Sloth は入力がディレクトリなら、ファイルごとに出力する。順番を固定するため、ファイル名順に 1 つずつ処理する
mapfile -t specs < <(find "${slo_dir}" -name '*.sloth.yaml' | sort)
if [[ ${#specs[@]} -eq 0 ]]; then
  echo "SLO の定義がない: ${slo_dir}/*.sloth.yaml" >&2
  exit 1
fi

for spec in "${specs[@]}"; do
  sloth validate --input "${spec}" >/dev/null 2>"${tmp}/sloth.log" || { cat "${tmp}/sloth.log" >&2; exit 1; }
  sloth generate --input "${spec}" --out "${tmp}/$(basename "${spec}" .sloth.yaml).rules.yaml" 2>"${tmp}/sloth.log" \
    || { cat "${tmp}/sloth.log" >&2; exit 1; }
done

# 生成したルールを promtool で検査する (同梱の Prometheus と同じ版。mise.toml)
promtool check rules "${tmp}"/*.rules.yaml >/dev/null

{
  echo "# Code generated by scripts/gen-slo-rules.sh from ${slo_dir}/*.sloth.yaml. DO NOT EDIT."
  echo "# OpenTelemetry Demo の chart に渡す values。同梱の Prometheus の serverFiles にルールを入れる。"
  echo "prometheus:"
  echo "  serverFiles:"
  # 【記録のルールとアラートのルールを 1 つのファイルに入れる】Prometheus はどちらの種類も、どのルールのファイルにも書ける。
  # Sloth の出力を分けずに済む
  echo "    alerting_rules.yml:"
  echo "      groups:"
  for rules in "${tmp}"/*.rules.yaml; do
    # Sloth の出力の先頭の `---`、コメント、`groups:` の行を除き、グループの一覧だけを字下げして並べる
    grep -vE '^(---|#|groups:)' "${rules}" | sed -e '/^$/d' -e 's/^/      /'
  done
} >"${tmp}/values.yaml"

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "${out}" "${tmp}/values.yaml"; then
    echo "【${out} が SLO の定義と一致しない】scripts/gen-slo-rules.sh を実行して、結果をコミットする" >&2
    exit 1
  fi
  echo "OK: ${out} は SLO の定義と一致している"
else
  cp "${tmp}/values.yaml" "${out}"
  echo "生成した: ${out}"
fi
